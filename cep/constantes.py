def factor(nombre: str, n: int) -> float:
    """Devuelve el factor `nombre` (d2, D3, D4, c4, B3, B4, A2, A3) para tamaño de subgrupo n."""
    n = int(n)
    if n not in _TABLA:
        raise ValueError(
            f"El tamaño de subgrupo n={n} está fuera de la tabla de constantes "
            f"({N_MIN} a {N_MAX})."
        )
    return _TABLA[n][_NOMBRES.index(nombre)]


def tabla_dataframe():
    """Tabla de constantes como DataFrame (para mostrarla en la app y el manual)."""
    import pandas as pd

    filas = [{"n": n, **dict(zip(_NOMBRES, v))} for n, v in _TABLA.items()]
    return pd.DataFrame(filas)
